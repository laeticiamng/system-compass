#!/usr/bin/env node

/**
 * Audit Script: Count RLS Tables
 * Note: This script counts tables from the types file
 * For accurate RLS status, use the Supabase linter tool
 */

const fs = require('fs');
const path = require('path');

const TYPES_FILE = path.join(__dirname, '../../src/integrations/supabase/types.ts');

function countRlsTables() {
  console.log('🔒 System Compass - RLS Tables Counter');
  console.log('========================================\n');

  if (!fs.existsSync(TYPES_FILE)) {
    console.error('❌ Types file not found:', TYPES_FILE);
    console.log('   This file is auto-generated by Supabase.');
    process.exit(1);
  }

  const content = fs.readFileSync(TYPES_FILE, 'utf-8');

  // Extract table names from the Tables section
  const tablesMatch = content.match(/Tables: \{([\s\S]*?)\n    \}/);
  
  if (!tablesMatch) {
    console.error('❌ Could not parse Tables section');
    process.exit(1);
  }

  // Find all table definitions (lines with Row:, Insert:, Update:)
  const tableNames = [];
  const tableRegex = /^\s{6}(\w+): \{$/gm;
  let match;
  
  while ((match = tableRegex.exec(tablesMatch[1])) !== null) {
    tableNames.push(match[1]);
  }

  // Remove duplicates and filter
  const uniqueTables = [...new Set(tableNames)];

  console.log(`Tables dans le schéma public: ${uniqueTables.length}`);
  console.log('─────────────────────────────────────\n');

  // Categorize tables
  const categories = {
    'User & Auth': uniqueTables.filter(t => 
      t.includes('profile') || t.includes('user_') || t.includes('subscriber')
    ),
    'Countries': uniqueTables.filter(t => 
      t.includes('countr') && !t.includes('snapshot')
    ),
    'TraceOS': uniqueTables.filter(t => 
      t.includes('traceos_')
    ),
    'B2B / Cases': uniqueTables.filter(t => 
      t.includes('case_') || t.includes('workspace_') || t.includes('b2b_')
    ),
    'Gamification': uniqueTables.filter(t => 
      t.includes('game') || t.includes('gamification') || t.includes('challenge')
    ),
    'Analytics': uniqueTables.filter(t => 
      t.includes('analytics') || t.includes('usage') || t.includes('activity')
    ),
    'AI & Generation': uniqueTables.filter(t => 
      t.includes('ai_') || t.includes('generation') || t.includes('translation')
    ),
    'Intel': uniqueTables.filter(t => 
      t.includes('intel') || t.includes('irreversa') || t.includes('latent')
    ),
    'Media': uniqueTables.filter(t => 
      t.includes('music')
    ),
    'Other': uniqueTables.filter(t => 
      t.includes('push_') || t.includes('event_') || t.includes('i18n')
    ),
  };

  Object.entries(categories).forEach(([category, tables]) => {
    if (tables.length > 0) {
      console.log(`📁 ${category} (${tables.length})`);
      tables.forEach(t => console.log(`   └─ ${t}`));
      console.log('');
    }
  });

  // Tables not categorized
  const categorized = Object.values(categories).flat();
  const uncategorized = uniqueTables.filter(t => !categorized.includes(t));
  
  if (uncategorized.length > 0) {
    console.log(`📁 Non catégorisées (${uncategorized.length})`);
    uncategorized.forEach(t => console.log(`   └─ ${t}`));
    console.log('');
  }

  console.log('─────────────────────────────────────');
  console.log(`TOTAL: ${uniqueTables.length} tables`);
  console.log('');
  console.log('ℹ️  Pour vérifier le statut RLS réel, utilisez:');
  console.log('   supabase--linter (dans Lovable)');
  console.log('');
  console.log(`✅ ${uniqueTables.length} tables dans le schéma`);

  return uniqueTables.length;
}

const count = countRlsTables();
process.exit(count > 0 ? 0 : 1);
